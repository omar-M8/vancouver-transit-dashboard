"""In-memory GTFS static lookups, loaded once at API startup.

The JSON files in backend/data/ are generated by scripts/build_static_data.py.
If they are missing (fresh clone), they are built on first load.
"""

import json
import time
from dataclasses import dataclass
from pathlib import Path

try:
    # Started from the repo root: `uvicorn backend.main:app`
    from .scripts.build_static_data import DATA_DIR, DATA_FILES, build_static_data
    from .stop_search import StopSearchIndex
except ImportError:
    # Started from inside backend/: `uvicorn main:app`
    from scripts.build_static_data import DATA_DIR, DATA_FILES, build_static_data
    from stop_search import StopSearchIndex

# TransLink republishes the schedule weekly
STALE_AFTER_SECONDS = 7 * 24 * 60 * 60

# Positions inside a trips_index.json row
TRIP_ROUTE_ID, TRIP_HEADSIGN, TRIP_DIRECTION_ID, TRIP_SHAPE_ID = range(4)


@dataclass
class StaticData:
    """GTFS static lookups held in memory; every field is keyed by id for O(1) access."""
    # stop_id -> {stop_id, stop_code, name, lat, lon}
    stops: dict[str, dict]
    # public stop_code (the number on the sign) -> stop_id
    stop_code_to_id: dict[str, str]
    # route_id -> {route_id, short_name, long_name, color, text_color, route_type}
    routes: dict[str, dict]
    # trip_id -> [route_id, headsign, direction_id, shape_id]
    trips: dict[str, list]
    # shape_id -> [[lon, lat], ...]
    shapes: dict[str, list[list[float]]]
    # route_id -> shape_ids, busiest first
    route_shape_ids: dict[str, list[str]]
    # stop_id -> route_ids serving it
    stop_routes: dict[str, list[str]]
    search: StopSearchIndex
    meta: dict

    def resolve_stop_id(self, stop: str) -> str | None:
        """Accept a public stop code ("50915") or a GTFS stop_id; return the stop_id."""
        if stop in self.stop_code_to_id:
            return self.stop_code_to_id[stop]
        if stop in self.stops:
            return stop
        return None

    def trip_headsign(self, trip_id: str) -> str | None:
        """Destination shown on the vehicle (e.g. "UBC"), or None for an unknown trip or blank headsign."""
        trip = self.trips.get(trip_id)
        return (trip[TRIP_HEADSIGN] or None) if trip else None

    def routes_for_stop(self, stop_id: str) -> list[dict]:
        """Route dicts serving a stop, in rider order (see route_sort_key); [] if none."""
        return [
            self.routes[route_id]
            for route_id in self.stop_routes.get(stop_id, [])
            if route_id in self.routes
        ]


def _read(data_dir: Path, name: str):
    """Parse one JSON file from the data directory."""
    with (data_dir / name).open(encoding="utf-8") as f:
        return json.load(f)


def load_static_data(data_dir: Path = DATA_DIR) -> StaticData:
    """Read backend/data/*.json into memory, building the files first if needed."""
    if not all((data_dir / name).exists() for name in DATA_FILES):
        print("--- Static GTFS data not found; building it (one-off, needs network) ---")
        build_static_data(data_dir=data_dir)

    started = time.time()
    stop_list = _read(data_dir, "stops.json")
    route_list = _read(data_dir, "routes.json")
    route_shapes = _read(data_dir, "route_shapes.json")
    meta = _read(data_dir, "meta.json")

    data = StaticData(
        stops={stop["stop_id"]: stop for stop in stop_list},
        stop_code_to_id={stop["stop_code"]: stop["stop_id"] for stop in stop_list if stop["stop_code"]},
        routes={route["route_id"]: route for route in route_list},
        trips=_read(data_dir, "trips_index.json"),
        shapes=route_shapes["shapes"],
        route_shape_ids=route_shapes["routes"],
        stop_routes=_read(data_dir, "stop_routes.json"),
        search=StopSearchIndex.build([
            {
                "stop_id": stop["stop_id"],
                "stop_code": stop["stop_code"],
                "stop_name": stop["name"],
                "lat": stop["lat"],
                "lon": stop["lon"],
            }
            for stop in stop_list
        ]),
        meta=meta,
    )

    age_days = (time.time() - meta.get("generated_at", 0)) / 86400
    print(
        f"--- Loaded static GTFS {meta.get('feed_version', '?')}: {len(data.stops)} stops, "
        f"{len(data.routes)} routes, {len(data.trips)} trips in {time.time() - started:.2f}s ---"
    )
    if age_days * 86400 > STALE_AFTER_SECONDS:
        print(
            f"--- Static GTFS data is {age_days:.0f} days old; "
            "refresh it with: python backend/scripts/build_static_data.py ---"
        )
    return data
