# GTFS static lookups (stops, routes, trips, shapes), generated by
# scripts/build_static_data.py and read into memory once.
_static_data: StaticData | None = None


def get_static() -> StaticData:
    """The shared StaticData, loaded on first use. Endpoints call this instead of touching the global."""
    global _static_data
    if _static_data is None:
        _static_data = load_static_data()
    return _static_data


@asynccontextmanager
async def lifespan(app: FastAPI):
    """FastAPI startup hook: load static data before serving so no request waits on it."""
    get_static()
    yield


