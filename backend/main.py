# TransLink GTFS-Realtime v3 feeds:
#   gtfsrealtime -> trip updates (arrival/delay estimates)
#   gtfsposition -> vehicle positions (lat/lon of every active bus/train)
#   gtfsalerts   -> service alerts
GTFS_RT_FEEDS = {"gtfsrealtime", "gtfsposition", "gtfsalerts"}
GTFS_RT_TIMEOUT_SECONDS = 10


async def get_feed(feed_name: str):
    """Helper function: Ensure we always have a fresh 30s copy of a GTFS-RT feed in RAM"""
    if feed_name not in GTFS_RT_FEEDS:
        raise ValueError(f"Unknown GTFS-RT feed: {feed_name}")

    current_time = time.time()
    cache_key = f"gtfs_rt_{feed_name}"  # each feed gets its own cache entry

    # If cache exists and is fresh (< 30s), return it immediately
    if cache_key in cache_memory and (current_time - cache_memory[cache_key]["timestamp"]< 30):
        print(f"--- Returned {feed_name} directly from Cache!! ---")
        return cache_memory[cache_key]["data"]

    #Otherwise, fetch full system feed from Translink
    else:
        print(f"--- Fetching fresh {feed_name} feed for all of Vancouver ---")
        url = f"https://gtfsapi.translink.ca/v3/{feed_name}"

        try:
            async with httpx.AsyncClient(timeout=GTFS_RT_TIMEOUT_SECONDS) as client:
                response = await client.get(url, params={"apikey": TRANSLINK_API_KEY})
        except httpx.TimeoutException:
            raise HTTPException(status_code=504, detail=f"Timed out fetching GTFS feed ({feed_name})")
        except httpx.HTTPError:
            raise HTTPException(status_code=502, detail=f"Failed to fetch GTFS feed ({feed_name})")

        if response.status_code != 200:
            raise HTTPException(status_code=response.status_code, detail=f"Failed to fetch GTFS feed ({feed_name})")

        # Parse Protobuf binary data
        feed = gtfs_realtime_pb2.FeedMessage()
        feed.ParseFromString(response.content)

        cache_memory[cache_key] = {
            "timestamp": current_time,
            "data": feed
        }

        return feed


def resolve_stop_ids(station_id: str) -> set[str]:
    """Translate a public stop code (e.g. "50915") into the internal stop_id
    the real-time feed uses. Falls back to treating the input as a stop_id."""
    stop_id = get_static().resolve_stop_id(station_id)
    return {stop_id} if stop_id else set()


def stop_payload(stop: dict) -> dict:
    """Public JSON shape of a stop (renames the internal "name" to "stop_name")."""
    return {
        "stop_id": stop["stop_id"],
        "stop_code": stop["stop_code"],
        "stop_name": stop["name"],
        "lat": stop["lat"],
        "lon": stop["lon"],
    }


@app.get("/stops/search")
async def search_stops(
    q: str = Query(..., min_length=1, max_length=100, description='Free text or a stop code, e.g. "49th and fraser" or "50915"'),
    limit: int = Query(10, ge=1, le=50),
):
    """
    Find stops by name or stop code. Words can be in any order, ordinals and
    street types are ignored, and small typos are tolerated ("frasr" finds
    Fraser St). A query of only digits also matches stop codes.

    One intersection usually has several stops (one per direction), so the
    results are meant to be shown as a pick-list using each result's "label".
    Pass a result's stop_code (or stop_id, if it has no code) to /transit/{station_id}.
    """
    terms, results = get_static().search.search(q, limit=limit)
    return {
        "query": q,
        "terms": terms,
        "results_found": len(results),
        "results": results,
    }


@app.get("/stops/{stop_id}")
async def get_stop(stop_id: str):
    """Stop details plus the routes serving it. Accepts a stop code or a GTFS stop_id."""
    static = get_static()
    resolved = static.resolve_stop_id(stop_id)
    if resolved is None:
        raise HTTPException(status_code=404, detail=f"Unknown stop: {stop_id}")
    return {
        **stop_payload(static.stops[resolved]),
        "routes": static.routes_for_stop(resolved),
    }


